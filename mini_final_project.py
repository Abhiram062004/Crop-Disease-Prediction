from sklearn.model_selection import train_test_split

def split_dataset(dataset_folder, output_folder, train_ratio=0.7, val_ratio=0.15, test_ratio=0.15):
    if not os.path.exists(output_folder):
        os.makedirs(output_folder)

    for class_name in os.listdir(dataset_folder):
        class_path = os.path.join(dataset_folder, class_name)

        if os.path.isdir(class_path):
            images = [f for f in os.listdir(class_path) if os.path.isfile(os.path.join(class_path, f))]
            train_images, remaining_images = train_test_split(images, train_size=train_ratio, random_state=42)
            val_images, test_images = train_test_split(remaining_images, train_size=val_ratio/(val_ratio + test_ratio), random_state=42)

            for image_name in train_images:
              src = os.path.join(class_path, image_name)
              dest = os.path.join(output_folder, "train", class_name)
              os.makedirs(dest, exist_ok=True)
              shutil.copy(src, dest)

            for image_name in val_images:
              src = os.path.join(class_path, image_name)
              dest = os.path.join(output_folder, "validation", class_name)
              os.makedirs(dest, exist_ok=True)
              shutil.copy(src, dest)

            for image_name in test_images:
              src = os.path.join(class_path, image_name)
              dest = os.path.join(output_folder, "test", class_name)
              os.makedirs(dest, exist_ok=True)
              shutil.copy(src, dest)

